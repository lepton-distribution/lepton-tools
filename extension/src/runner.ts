// Exécution de lepton pour les commandes (avec notification) et les observateurs (silencieuse) ;
// une seule file : jamais deux lepton à la fois sur le rootstock.
import * as path from "node:path";
import * as vscode from "vscode";
import { SerialQueue } from "./batch";
import { EXIT_INTERRUPT, EXIT_OK, EXIT_USER, LeptonResult, lastMessage, resolveLepton, runLepton } from "./lepton";

export class LeptonRunner implements vscode.Disposable {
  private readonly queue = new SerialQueue();
  private readonly changed = new vscode.EventEmitter<void>();
  /** Émis après chaque commande lancée par l'utilisateur (la graine a pu changer). */
  readonly onDidRunCommand = this.changed.event;

  constructor(readonly output: vscode.OutputChannel) {}

  dispose(): void {
    this.changed.dispose();
  }

  /** Répertoire de travail : celui de l'espace généré (rootstock), sinon le premier dossier ouvert. */
  cwd(): string | undefined {
    const ws = vscode.workspace.workspaceFile;
    if (ws?.scheme === "file") {
      return path.dirname(ws.fsPath);
    }
    return vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;
  }

  private exe(): string {
    return resolveLepton(vscode.workspace.getConfiguration("lepton").get<string>("path", ""));
  }

  /** `echoStdout` faux : sortie standard (JSON lu par l'extension) gardée hors du canal. */
  private spawn(args: string[], cwd: string, signal?: AbortSignal, echoStdout = true): Promise<LeptonResult> {
    const exe = this.exe();
    this.output.appendLine(`$ ${exe} ${args.join(" ")}    (${cwd})`);
    return runLepton(exe, args, cwd, (t, stream) => {
      if (echoStdout || stream === "stderr") {
        this.output.append(t);
      }
    }, signal,
      (e) => vscode.l10n.t("lepton not found: {0} (setting lepton.path)", e));
  }

  /** Appel silencieux (observateurs, lectures JSON) : sortie dans le canal seulement, sauf le JSON
   *  d'une commande `--json`. */
  async exec(args: string[]): Promise<LeptonResult | undefined> {
    const cwd = this.cwd();
    if (!cwd) {
      return undefined;
    }
    return this.queue.run(async () => {
      const result = await this.spawn(args, cwd, undefined, !args.includes("--json"));
      this.output.appendLine(`→ code ${result.code}\n`);
      return result;
    });
  }

  /** Commande de l'utilisateur : progression annulable, puis notification du résultat. */
  async run(title: string, args: string[], opts: { show?: boolean; quiet?: boolean } = {}):
    Promise<LeptonResult | undefined> {
    const cwd = this.cwd();
    if (!cwd) {
      vscode.window.showErrorMessage(
        vscode.l10n.t("Lepton: no folder open (open the workspace generated by lepton generate)."));
      return undefined;
    }
    if (opts.show) {
      this.output.show(true);
    }
    const result = await this.queue.run(async () => vscode.window.withProgress(
      { location: vscode.ProgressLocation.Notification, title: `lepton: ${title}`, cancellable: true },
      (_progress, token) => {
        const abort = new AbortController();
        token.onCancellationRequested(() => abort.abort());
        return this.spawn(args, cwd, abort.signal);
      },
    ));
    this.output.appendLine(`→ code ${result.code}\n`);
    void this.report(title, result, opts.quiet ?? false);
    this.changed.fire();
    return result;
  }

  /** Notification d'un résultat ; succès silencieux si `quiet`. */
  async report(title: string, result: LeptonResult, quiet: boolean): Promise<void> {
    const showOutput = vscode.l10n.t("Show output");
    let choice: string | undefined;
    if (result.code === EXIT_OK) {
      if (!quiet) {
        vscode.window.showInformationMessage(vscode.l10n.t("lepton: {0} — done", title));
      }
      return;
    } else if (result.code === EXIT_INTERRUPT) {
      choice = await vscode.window.showWarningMessage(vscode.l10n.t("lepton: {0} — interrupted", title), showOutput);
    } else if (result.code === EXIT_USER) {
      choice = await vscode.window.showWarningMessage(
        `lepton: ${title} — ${lastMessage(result) || vscode.l10n.t("refused")}`, showOutput);
    } else {
      choice = await vscode.window.showErrorMessage(
        vscode.l10n.t("lepton: {0} — failed (code {1}) {2}", title, result.code, lastMessage(result)), showOutput);
    }
    if (choice === showOutput) {
      this.output.show();
    }
  }
}
